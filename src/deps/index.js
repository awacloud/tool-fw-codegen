/**
 * Generated subtrees never scanned for `deps` injection: the prebuilt bundles
 * are build artefacts (regenerated by `tools/generate-prebuilds.mjs`) whose
 * `dependencies` list fw module names — injecting into them would both edit a
 * generated file and pollute the name index.
 */
export const DEFAULT_IGNORE = ['bundles/prebuilt/**'];

/**
 * Parse the `deps` subcommand argv.
 * @param {string[]} argv
 * @returns {{ dryRun: boolean, check: boolean, pkg: string|null, src: string|null, ignore: string[] }}
 */
function parseArgs(argv) {
    const opts = { dryRun: false, check: false, pkg: null, src: null, ignore: [] };
    /** Consume the value of a value-taking flag, rejecting a missing one. */
    const value = (flag, i) => {
        const v = argv[i];
        if (v === undefined || v.startsWith('--')) {
            throw new Error(`Flag ${flag} requires a value. Run with --help.`);
        }
        return v;
    };
    for (let i = 0; i < argv.length; i++) {
        const a = argv[i];
        if (a === '--dry-run') opts.dryRun = true;
        else if (a === '--check') opts.check = true;
        else if (a === '--pkg') opts.pkg = value(a, ++i);
        else if (a === '--src') opts.src = value(a, ++i);
        else if (a === '--ignore') opts.ignore.push(value(a, ++i));
        else if (a.startsWith('--')) throw new Error(`Unknown flag: ${a}. Run with --help.`);
        else throw new Error(`Unexpected positional argument: ${a}`);
    }
    return opts;
}

/** Resolve the `src/` scan root from the seam options. */
function resolveSrcDir({ pkg = null, src = null } = {}) {
    if (src) return resolve(src);
    return resolve(pkg ?? process.cwd(), 'src');
}

// ─── Scan filtering (defect 1) ───

/**
 * Scan `srcDir` WITHOUT the duplicate-name reconciliation of `scanAll`.
 *
 * `scanAll` throws on the first duplicate module name, which happens BEFORE
 * any ignore filter could apply — so a generated bundle re-declaring a real
 * module's name would abort the whole package. The dedup contract is not
 * dropped: `filterScan` re-applies it over the SURVIVING entries.
 *
 * @param {string} srcDir
 * @returns {{ byFile: Map<string, import('@awacloud/tool-fw-bundler/modlib').ModuleInfo>, unparseable: import('@awacloud/tool-fw-bundler/modlib').ModuleInfo[] }}
 */
function rawScan(srcDir) {
    const byFile = new Map();
    const unparseable = [];
    for (const file of listSourceFiles(srcDir)) {
        const info = parseFile(file);
        if (!info) continue;
        if (info._unparseable) unparseable.push(info);
        else byFile.set(file, info);
    }
    return { byFile, unparseable };
}

/**
 * Make an absolute module path relative to `srcDir`, POSIX-normalized.
 * @param {string} file
 * @param {string} srcDir
 * @returns {string}
 */
function relPosix(file, srcDir) {
    return relative(srcDir, file).replace(/\\/g, '/');
}

/**
 * Drop every scanned entry whose src-relative path matches one of the ignore
 * globs (default ignore unioned with the caller's), then rebuild BOTH indexes
 * from the survivors — an ignored file must never be picked as an import
 * target, even for a name it duplicates.
 *
 * Pure: the input scan is not mutated.
 *
 * @param {{ byFile: Map<string, any>, unparseable: any[] }} scanned
 * @param {string} srcDir
 * @param {string[]} [ignore]  Extra globs, unioned with {@link DEFAULT_IGNORE}.
 * @returns {{ byName: Map<string, any>, byFile: Map<string, any>, unparseable: any[], ignored: string[] }}
 */
export function filterScan(scanned, srcDir, ignore = []) {
    const globs = [...DEFAULT_IGNORE, ...ignore].map((p) => new Bun.Glob(p));
    const isIgnored = (file) => {
        const rel = relPosix(file, srcDir);
        return globs.some((g) => g.match(rel));
    };

    const byFile = new Map();
    const byName = new Map();
    const ignored = [];
    for (const [file, info] of scanned.byFile) {
        if (isIgnored(file)) { ignored.push(file); continue; }
        byFile.set(file, info);
        const prev = byName.get(info.moduleName);
        if (prev) {
            throw new Error(
                `[codegen-deps] duplicate module name "${info.moduleName}" :\n` +
                    `  ${prev.file}\n  ${file}`
            );
        }
        byName.set(info.moduleName, info);
    }
    const unparseable = scanned.unparseable.filter((u) => {
        if (isIgnored(u.file)) { ignored.push(u.file); return false; }
        return true;
    });
    return { byName, byFile, unparseable, ignored };
}

// ─── Workspace sibling resolution (addendum A2) ───

/** @type {Map<string, Map<string, string>>} rootDir → (package name → dir) */
const WORKSPACE_CACHE = new Map();

/**
 * Walk up from `fromDir` to the nearest `package.json` declaring a
 * `workspaces` array — the workspace root.
 *
 * @param {string} fromDir
 * @returns {{ root: string, globs: string[] } | null}
 */
function findWorkspaceRoot(fromDir) {
    let dir = resolve(fromDir);
    for (;;) {
        const manifest = join(dir, 'package.json');
        if (existsSync(manifest)) {
            try {
                const pkg = JSON.parse(readFileSync(manifest, 'utf8'));
                if (Array.isArray(pkg.workspaces)) return { root: dir, globs: pkg.workspaces };
            } catch { /* malformed manifest — keep walking up */ }
        }
        const parent = resolve(dir, '..');
        if (parent === dir) return null;
        dir = parent;
    }
}

/**
 * Resolve a workspace package NAME to its directory, FS-only.
 *
 * Deliberately does NOT consult `node_modules`: a workspace symlink can be
 * stale or absent (an incremental `bun install` does not always rematerialize
 * a nested link), whereas the root manifest's `workspaces` globs are the
 * declarative source of truth. Package code is never imported.
 *
 * @param {string} name     e.g. `@awacloud/fonts`
 * @param {string} fromDir  Any dir inside the workspace.
 * @returns {string|null}   Absolute package dir, or `null` when unknown.
 */
export function resolveWorkspacePackage(name, fromDir) {
    const ws = findWorkspaceRoot(fromDir);
    if (!ws) return null;

    let index = WORKSPACE_CACHE.get(ws.root);
    if (!index) {
        index = new Map();
        const negations = ws.globs
            .filter((g) => g.startsWith('!'))
            .map((g) => new Bun.Glob(g.slice(1)));
        for (const glob of ws.globs) {
            if (glob.startsWith('!')) continue;
            for (const hit of new Bun.Glob(`${glob}/package.json`).scanSync({ cwd: ws.root })) {
                const rel = hit.replace(/\\/g, '/');
                const dirRel = rel.slice(0, -'/package.json'.length);
                if (negations.some((n) => n.match(dirRel))) continue;
                try {
                    const pkg = JSON.parse(readFileSync(join(ws.root, hit), 'utf8'));
                    if (typeof pkg.name === 'string' && !index.has(pkg.name)) {
                        index.set(pkg.name, join(ws.root, dirRel));
                    }
                } catch { /* unreadable manifest — skip */ }
            }
        }
        WORKSPACE_CACHE.set(ws.root, index);
    }
    return index.get(name) ?? null;
}

/**
 * Turn an absolute source file of `pkgDir` into its PUBLIC import specifier,
 * by inverting the package's `exports` map. Exact targets and single-`*`
 * wildcard patterns are supported.
 *
 * Returns `null` when the file is not publicly exported — the caller must then
 * treat the name as unresolved rather than reach into the package with a deep
 * relative path.
 *
 * @param {string} pkgDir
 * @param {string} file    Absolute path inside `pkgDir`.
 * @returns {string|null}  e.g. `@awacloud/fonts/embed-pdf/subsetForPdf`
 */
export function publicSubpathFor(pkgDir, file) {
    let pkg;
    try { pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')); }
    catch { return null; }
    if (!pkg || typeof pkg.name !== 'string' || !pkg.exports) return null;

    const rel = './' + relPosix(file, pkgDir);
    /** @type {string|null} */
    let wildcard = null;

    for (const [subpath, target] of Object.entries(pkg.exports)) {
        if (typeof target !== 'string') continue;          // conditional exports: out of scope
        if (target === rel) {
            return subpath === '.' ? pkg.name : `${pkg.name}/${subpath.replace(/^\.\//, '')}`;
        }
        if (!subpath.includes('*') || !target.includes('*')) continue;
        const [pre, post] = target.split('*');
        if (!rel.startsWith(pre) || !rel.endsWith(post) || rel.length < pre.length + post.length) continue;
        const stem = rel.slice(pre.length, rel.length - post.length);
        // Exact matches win over patterns — keep the first pattern hit as fallback.
        wildcard ??= `${pkg.name}/${subpath.replace(/^\.\//, '').replace('*', stem)}`;
    }
    return wildcard;
}

// ─── Cross-package name resolution (defect 2 + addendum A2) ───

/**
 * Blank out every COMMENT — line and block — replacing each stripped character
 * with a space so that **byte offsets and line numbers are preserved**.
 *
 * String and template literals are deliberately kept intact: the import
 * parsers below read the specifier out of `from '<specifier>'`, so blanking
 * literals would defeat them. Literals are still *scanned over*, so a `//` or
 * `/*` appearing inside a string never starts a phantom comment.
 *
 * Addendum A3. The import parsers match text, and a documented usage example
 * is text: `ooxml/src/extra/wml-run-formatting.js` carries
 * `import { xml as xmlMod } from '@awacloud/fw/io/codec/xml.js';` in its JSDoc
 * header, which layer 1 reported as an in-scope binding — yielding
 * `deps: [xmlMod]` with no import at all. A comment is not a binding.
 *
 * @param {string} src
 * @returns {string}
 */
export function stripComments(src) {
    const out = src.split('');
    const blank = (from, to) => {
        for (let k = from; k < to && k < out.length; k++) {
            if (out[k] !== '\n') out[k] = ' ';
        }
    };
    let i = 0;
    while (i < src.length) {
        const c = src[i];
        const next = src[i + 1];
        if (c === '/' && next === '/') {
            let j = src.indexOf('\n', i);
            if (j === -1) j = src.length;
            blank(i, j);
            i = j;
        } else if (c === '/' && next === '*') {
            let j = src.indexOf('*/', i + 2);
            j = j === -1 ? src.length : j + 2;
            blank(i, j);
            i = j;
        } else if (c === "'" || c === '"' || c === '`') {
            // Scan over the literal without touching it (see the note above).
            let j = i + 1;
            while (j < src.length) {
                if (src[j] === '\\') { j += 2; continue; }
                if (src[j] === c) { j++; break; }
                if (c !== '`' && src[j] === '\n') break;   // unterminated: bail out
                j++;
            }
            i = j;
        } else {
            i++;
        }
    }
    return out.join('');
}

/**
 * Collect every identifier bound at the TOP LEVEL of a module source: the
 * local names of its named/namespace/default imports (alias-aware) and its
 * own `const`/`let`/`var`/`function`/`class` declarations.
 *
 * Addendum A3 — this is the oracle behind the emit guard in
 * {@link rewriteFile}. Only column-0 declarations count: an indented `const md`
 * inside a factory body is function-scoped and must NOT be mistaken for a
 * module-level binding (that exact shape exists in `md.js`).
 *
 * @param {string} src
 * @returns {Set<string>}
 */
function topLevelBindings(src) {
    const code = stripComments(src);
    const out = new Set();

    const named = /import\s*\{([^}]*)\}\s*from\s*['"][^'"]+['"]/g;
    let m;
    while ((m = named.exec(code)) !== null) {
        for (const part of m[1].split(',')) {
            const t = part.trim();
            if (!t) continue;
            const [imported, alias] = t.split(/\s+as\s+/);
            out.add((alias ?? imported).trim());
        }
    }
    const ns = /import\s*(?:(\w+)\s*,\s*)?\*\s*as\s+(\w+)\s*from/g;
    while ((m = ns.exec(code)) !== null) {
        if (m[1]) out.add(m[1]);
        out.add(m[2]);
    }
    const def = /import\s+(\w+)\s*(?:,|from)/g;
    while ((m = def.exec(code)) !== null) out.add(m[1]);

    const decl = /(?:^|\n)(?:export\s+)?(?:const|let|var|function\*?|class)\s+(\w+)/g;
    while ((m = decl.exec(code)) !== null) out.add(m[1]);

    return out;
}

/**
 * Parse the static named imports coming from a PACKAGE specifier (anything not
 * starting with `.` or `/`).
 *
 * Generalized twice: fw-only → `@awacloud/` (LIGHT_9) → any package scope
 * (LIGHT_10). The scope is not the safety boundary — the `fw_require` /
 * `pkg_require` guard arrays are, and layer 1 only ever REUSES a binding the
 * descriptor already imports. Keeping it scope-agnostic is what lets the tool
 * serve a workspace whose packages are not named `@awacloud/*`.
 *
 * @param {string} src
 * @returns {{ imported: string, local: string, specifier: string }[]}
 */
function parsePackageImports(src) {
    const out = [];
    const code = stripComments(src);
    const re = /import\s*\{([^}]*)\}\s*from\s*['"]([^.\/'"][^'"]*)['"]/g;
    let m;
    while ((m = re.exec(code)) !== null) {
        for (const part of m[1].split(',')) {
            const t = part.trim();
            if (!t) continue;
            const [imported, alias] = t.split(/\s+as\s+/);
            out.push({
                imported: imported.trim(),
                local: (alias ?? imported).trim(),
                specifier: m[2],
            });
        }
    }
    return out;
}

/**
 * Parse `import * as <ns> from '<package>';` namespace imports.
 * @param {string} src
 * @returns {Map<string, string>}  local namespace → package name
 */
function parseNamespaceImports(src) {
    const out = new Map();
    const code = stripComments(src);
    const re = /import\s*\*\s*as\s+(\w+)\s*from\s*['"]([^.\/'"][^'"]*)['"]/g;
    let m;
    while ((m = re.exec(code)) !== null) out.set(m[1], m[2]);
    return out;
}

/**
 * Parse the entries of an `export const <name> = [ ... ];` array literal into
 * plain identifiers and namespace spreads.
 *
 * Both `fw_require` and `pkg_require` are GUARDS: they enumerate exactly what
 * the package expects to be injected in package mode, so only what they list
 * is eligible for resolution.
 *
 * @param {string} src
 * @param {string} name
 * @returns {{ ids: Set<string>, spreads: { ns: string, field: string }[] }}
 */
function parseRequireArray(src, name) {
    const m = src.match(new RegExp(`export\\s+const\\s+${name}\\s*=\\s*\\[([\\s\\S]*?)\\]`));
    const ids = new Set();
    const spreads = [];
    if (!m) return { ids, spreads };
    for (const raw of m[1].split(',')) {
        const t = raw.trim().replace(/\/\/.*$/, '').trim();
        if (!t) continue;
        const spread = t.match(/^\.\.\.\s*(\w+)\s*\.\s*(\w+)$/);
        if (spread) { spreads.push({ ns: spread[1], field: spread[2] }); continue; }
        if (/^\w+$/.test(t)) ids.add(t);
    }
    return { ids, spreads };
}

/**
 * Parse the static RELATIVE named imports of a source.
 * @param {string} src
 * @returns {{ imported: string, local: string, rel: string }[]}
 */
function parseRelativeImports(src) {
    const out = [];
    const code = stripComments(src);
    const re = /import\s*\{([^}]*)\}\s*from\s*['"](\.[^'"]+)['"]/g;
    let m;
    while ((m = re.exec(code)) !== null) {
        for (const part of m[1].split(',')) {
            const t = part.trim();
            if (!t) continue;
            const [imported, alias] = t.split(/\s+as\s+/);
            out.push({ imported: imported.trim(), local: (alias ?? imported).trim(), rel: m[2] });
        }
    }
    return out;
}

/** Resolve a package's entry file from its manifest (`exports["."]` ?? `main`). */
function entryFileOf(pkgDir) {
    try {
        const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
        const dot = typeof pkg.exports?.['.'] === 'string' ? pkg.exports['.'] : null;
        const rel = dot ?? (typeof pkg.main === 'string' ? pkg.main : 'src/main.js');
        return resolve(pkgDir, rel);
    } catch {
        return join(pkgDir, 'src', 'main.js');
    }
}

/**
 * Build the static cross-package name resolver for a package.
 *
 * Four ordered layers for a name absent from the package's own (filtered)
 * scan. Nothing is ever imported or executed — all four parse text only, and
 * every emitted specifier is either copied verbatim from a real import or
 * derived from a sibling's PUBLIC `exports` map.
 *
 *   1. the descriptor file's own `@awacloud/...` named imports (already in scope);
 *   2. the entry `main.js` `@awacloud/fw/...` imports ∩ its `fw_require` guard;
 *   3. the entry `main.js` named `@awacloud/...` imports ∩ its `pkg_require` guard;
 *   4. the entry `main.js` `pkg_require` NAMESPACE SPREADS
 *      (`import * as ns from '@awacloud/<pkg>'` + `...ns.<field>`): the sibling
 *      package is located through the workspace manifest, its own entry is
 *      parsed, and the identifiers of its `<field>` array act as the guard.
 *      A sibling binding imported relatively maps to its public subpath; one
 *      imported from `@awacloud/...` keeps that specifier verbatim.
 *   → otherwise unresolved.
 *
 * @param {string} srcDir
 * @returns {(depName: string, fileSrc: string) => { identifier: string, specifier: string, needsImport: boolean } | null}
 */
function createNameResolver(srcDir) {
    /** @type {{ fw: any[], pkg: any[], spreads: { ns: string, field: string }[], namespaces: Map<string, string> } | undefined} */
    let entry;
    const fromEntry = () => {
        if (entry !== undefined) return entry;
        const mainFile = join(srcDir, 'main.js');
        if (!existsSync(mainFile)) {
            return (entry = { fw: [], pkg: [], spreads: [], namespaces: new Map() });
        }
        const src = readFileSync(mainFile, 'utf8');
        const awa = parsePackageImports(src);
        const fwGuard = parseRequireArray(src, 'fw_require');
        const pkgGuard = parseRequireArray(src, 'pkg_require');
        entry = {
            fw: awa.filter((e) => e.specifier.startsWith('@awacloud/fw/') && fwGuard.ids.has(e.local)),
            pkg: awa.filter((e) => pkgGuard.ids.has(e.local)),
            spreads: pkgGuard.spreads,
            namespaces: parseNamespaceImports(src),
        };
        return entry;
    };

    /** @type {Map<string, { specifier: string, identifier: string } | null>} */
    const siblingCache = new Map();

    /**
     * Layer 4 — look a name up in a sibling package's guarded export set.
     * @param {string} depName
     */
    const fromSiblings = (depName) => {
        if (siblingCache.has(depName)) return siblingCache.get(depName);
        let hit = null;
        const { spreads, namespaces } = fromEntry();
        for (const { ns, field } of spreads) {
            const pkgName = namespaces.get(ns);
            if (!pkgName) continue;                             // not a namespace import
            const pkgDir = resolveWorkspacePackage(pkgName, srcDir);
            if (!pkgDir) continue;                              // unknown sibling → unresolved
            const mainFile = entryFileOf(pkgDir);
            if (!existsSync(mainFile)) continue;
            const src = readFileSync(mainFile, 'utf8');
            const guard = parseRequireArray(src, field).ids;     // the spread field IS the guard

            const viaAwa = parsePackageImports(src).find(
                (e) => guard.has(e.local) && (e.local === depName || e.imported === depName)
            );
            if (viaAwa) { hit = { specifier: viaAwa.specifier, identifier: viaAwa.imported }; break; }

            const viaRel = parseRelativeImports(src).find(
                (e) => guard.has(e.local) && (e.local === depName || e.imported === depName)
            );
            if (!viaRel) continue;
            // Never reach into a sibling with a private deep path.
            const subpath = publicSubpathFor(pkgDir, resolve(mainFile, '..', viaRel.rel));
            if (!subpath) continue;
            hit = { specifier: subpath, identifier: viaRel.imported };
            break;
        }
        siblingCache.set(depName, hit);
        return hit;
    };

    const match = (entries, depName) =>
        entries.find((e) => e.local === depName || e.imported === depName) ?? null;

    return (depName, fileSrc) => {
        // 1 — already imported by the descriptor: reuse the in-scope binding.
        const own = match(parsePackageImports(fileSrc), depName);
        if (own) return { identifier: own.local, specifier: own.specifier, needsImport: false };

        const e = fromEntry();
        // 2 / 3 — the entry's own guarded imports.
        const viaEntry = match(e.fw, depName) ?? match(e.pkg, depName);
        if (viaEntry) {
            return { identifier: viaEntry.imported, specifier: viaEntry.specifier, needsImport: true };
        }
        // 4 — a sibling package reached through a pkg_require spread.
        const viaSibling = fromSiblings(depName);
        if (viaSibling) {
            return { identifier: viaSibling.identifier, specifier: viaSibling.specifier, needsImport: true };
        }
        return null;
    };
}

/**
 * Inject the `deps: [...]` field plus the sibling `import { dep } from ...`
 * statements into a single module source.
 *
 * A module is rewritten ALL-OR-NOTHING: if at least one dependency name can
 * be resolved neither in the package nor against `@awacloud/fw`, the module is
 * skipped (`kind: 'skip'`) and no partial `deps` array is ever invented.
 *
 * @param {import('@awacloud/tool-fw-bundler/modlib').ModuleInfo} info
 * @param {Map<string, import('@awacloud/tool-fw-bundler/modlib').ModuleInfo>} byName
 * @param {(depName: string, fileSrc: string) => { identifier: string, specifier: string, needsImport: boolean } | null} resolveName
 * @returns {{ kind: 'plan', updatedSrc: string, addedImports: string[] } | { kind: 'skip', unresolved: string[] } | null}
 *   `null` when nothing needs to change.
 */
function rewriteFile(info, byName, resolveName) {
    if (info.hasDepsField) return null;
    if (info.dependencies.length === 0) return null;
    if (info.dependenciesEnd < 0) return null;

    const src = readFileSync(info.file, 'utf8');
    const bound = topLevelBindings(src);

    // Resolve each dep name: sibling module first, then the fw tree.
    /** @type {{ identifier: string, binding: string, importFrom: string|null }[]} */
    const resolvedDeps = [];
    /** @type {string[]} */
    const unresolved = [];
    for (const depName of info.depNames) {
        const target = byName.get(depName);
        if (target) {
            // A3 — the module `name:` is NOT necessarily the exported JS
            // binding (`md.js` is `name: 'md'` / `export const mdMod`).
            // `deps` must read as the dependency name (validate-deps compares
            // deps[i] to dependencies[i] textually), so when they differ the
            // import is ALIASED rather than the array renamed.
            const binding = target.bindingName || depName;
            if (binding !== depName && bound.has(depName)) {
                // Aliasing to `depName` would shadow an existing top-level
                // binding — skip rather than silently capture it.
                unresolved.push(depName);
                continue;
            }
            resolvedDeps.push({
                identifier: depName,
                binding,
                importFrom: relativeImport(info.file, target.file),
            });
            continue;
        }
        const fw = resolveName(depName, src);
        if (fw) {
            resolvedDeps.push({
                identifier: fw.identifier,
                binding: fw.identifier,
                importFrom: fw.needsImport ? fw.specifier : null,
            });
            continue;
        }
        unresolved.push(depName);
    }
    if (unresolved.length > 0) return { kind: 'skip', unresolved };

    // ─── 1. Inject imports at the top, after any existing `import ... from ...;`.
    const lines = src.split('\n');
    let lastImportLine = -1;
    let firstNonHeaderLine = -1;
    for (let i = 0; i < lines.length; i++) {
        const trimmed = lines[i].trim();
        if (/^import\s.+from\s+['"][^'"]+['"];?/.test(trimmed)) {
            lastImportLine = i;
            continue;
        }
        // Track first line that's neither blank nor a comment for fallback.
        if (
            firstNonHeaderLine === -1 &&
            trimmed !== '' &&
            !trimmed.startsWith('//') &&
            !trimmed.startsWith('/*') &&
            !trimmed.startsWith('*')
        ) {
            firstNonHeaderLine = i;
        }
        if (trimmed.startsWith('export ')) break;
    }

    // Determine which deps are NOT already imported by the source (avoid dupes).
    const existingImports = new Set();
    const importBindingRe = /^import\s*\{\s*([^}]+)\s*\}\s*from/;
    for (const ln of lines) {
        const m = ln.trim().match(importBindingRe);
        if (!m) continue;
        for (const part of m[1].split(',')) {
            existingImports.add(part.trim().split(/\s+as\s+/)[0]);
        }
    }

    /** @type {string[]} */
    const addedImports = [];
    /** Local names this rewrite brings into scope. */
    const addedBindings = new Set();
    for (const { identifier, binding, importFrom } of resolvedDeps) {
        if (importFrom === null) continue;      // already in scope (descriptor-local fw import)
        if (existingImports.has(identifier)) continue;
        existingImports.add(identifier);        // a name may repeat across dependencies
        addedBindings.add(identifier);
        const clause = binding === identifier ? identifier : `${binding} as ${identifier}`;
        addedImports.push(`import { ${clause} } from '${importFrom}';`);
    }

    // ─── A3 emit guard ───────────────────────────────────────────────────────
    // Every identifier about to land in `deps: [...]` must be a REAL binding:
    // imported by this rewrite, already imported, or declared at top level.
    // Without this, a resolver bug writes a file that parses but throws at
    // import time — exit 0, no warning, caught only by the consumer's suite
    // (office/BATCH_9 lost a wave to exactly that). A phantom identifier is
    // reported as unresolved, reusing the existing skip-and-continue path.
    const phantom = resolvedDeps
        .map((d) => d.identifier)
        .filter((id) => !addedBindings.has(id) && !bound.has(id));
    if (phantom.length > 0) return { kind: 'skip', unresolved: [...new Set(phantom)] };

    const insertAt =
        lastImportLine >= 0
            ? lastImportLine + 1
            : firstNonHeaderLine >= 0
                ? firstNonHeaderLine
                : 0;

    if (addedImports.length > 0) {
        // Add a blank line separator if we're inserting at top-of-file.
        const inject =
            lastImportLine < 0 ? [...addedImports, ''] : addedImports;
        lines.splice(insertAt, 0, ...inject);
    }

    let updatedSrc = lines.join('\n');

    // ─── 2. Inject `deps: [...]` immediately after `dependencies: [...]`.
    //
    // We rely on the original `dependenciesEnd` offset BUT it was computed on
    // the pre-edit source. Recompute the dependenciesEnd by searching from the
    // (now-shifted) block. Safer than offset arithmetic given variable line
    // endings.
    const depsRe =
        /(^|[\s,{])dependencies\s*:\s*\[[\s\S]*?\](?!\s*,?\s*deps\s*:)/m;
    const depsMatch = updatedSrc.match(depsRe);
    if (!depsMatch) {
        throw new Error(
            `could not relocate "dependencies" in updated source of ${info.file}`
        );
    }
    const depsEnd =
        /** @type {number} */ (depsMatch.index) +
        depsMatch[0].length;

    // Determine indentation by looking at the line containing `dependencies:`.
    const lineStart = updatedSrc.lastIndexOf('\n', depsMatch.index) + 1;
    const lineText = updatedSrc.slice(lineStart, depsMatch.index + depsMatch[1].length);
    const indentMatch = lineText.match(/^(\s*)/);
    const indent = indentMatch ? indentMatch[1] : '    ';

    const depsLiteral = `,\n${indent}deps: [${resolvedDeps.map((d) => d.identifier).join(', ')}]`;
    updatedSrc =
        updatedSrc.slice(0, depsEnd) + depsLiteral + updatedSrc.slice(depsEnd);

    return { kind: 'plan', updatedSrc, addedImports };
}

// ─── BL-5 — the content leg (`--check` on an ALREADY-POPULATED module) ─────

/**
 * Extract the identifiers currently written into a module's on-disk
 * `deps: [...]`, comment-stripped and in order. `null` when no such field is
 * present (the caller only calls this for `info.hasDepsField === true`, so
 * `null` here would itself be a parsing anomaly, treated as drift).
 *
 * @param {string} src
 * @returns {string[] | null}
 */
function actualDepsOf(src) {
    const m = /(^|[\s,{])deps\s*:\s*\[([^\]]*)\]/.exec(stripComments(src));
    if (!m) return null;
    return m[2].split(',').map((s) => s.trim()).filter(Boolean);
}

/**
 * Re-derive the identifiers that SHOULD sit in `deps: [...]` for a module,
 * given its current `dependencies` — the read-only counterpart of the
 * resolution `rewriteFile` performs when WRITING the field for the first
 * time. Unlike `rewriteFile`, this never plans an edit and never needs the
 * write-time shadow check: a sibling dependency's `deps` entry is always the
 * dependency NAME itself (validate-deps compares `deps[i]` to
 * `dependencies[i]` textually — see the A3 note above `rewriteFile`),
 * regardless of whether its JS binding differs.
 *
 * @param {import('@awacloud/tool-fw-bundler/modlib').ModuleInfo} info
 * @param {Map<string, import('@awacloud/tool-fw-bundler/modlib').ModuleInfo>} byName
 * @param {(depName: string, fileSrc: string) => { identifier: string, specifier: string, needsImport: boolean } | null} resolveName
 * @param {string} src
 * @returns {{ identifiers: string[] } | { unresolved: string[] }}
 */
function resolveExpectedIdentifiers(info, byName, resolveName, src) {
    const identifiers = [];
    const unresolved = [];
    for (const depName of info.depNames) {
        if (byName.has(depName)) { identifiers.push(depName); continue; }
        const fw = resolveName(depName, src);
        if (fw) { identifiers.push(fw.identifier); continue; }
        unresolved.push(depName);
    }
    return unresolved.length > 0 ? { unresolved } : { identifiers };
}

/**
 * Find every already-populated module (`hasDepsField === true`) whose
 * on-disk `deps: [...]` no longer matches what its `dependencies` resolve
 * to — a rename, a hand-edit, or a stale copy-paste that the presence-only
 * `hasDepsField` check cannot see (BL-5).
 *
 * A module whose expected identifiers cannot be re-derived at all (a name
 * that no longer resolves anywhere) is reported too, with `expected: null` —
 * the recorded `deps` cannot be vouched for, which is itself worth failing
 * `--check` over rather than passing silently.
 *
 * @param {Map<string, import('@awacloud/tool-fw-bundler/modlib').ModuleInfo>} byFile
 * @param {Map<string, import('@awacloud/tool-fw-bundler/modlib').ModuleInfo>} byName
 * @param {(depName: string, fileSrc: string) => { identifier: string, specifier: string, needsImport: boolean } | null} resolveName
 * @returns {{ file: string, moduleName: string, expected: string[]|null, found: string[]|null }[]}
 */
function computeContentDrift(byFile, byName, resolveName) {
    const drift = [];
    for (const info of byFile.values()) {
        if (!info.hasDepsField || info.depNames.length === 0) continue;
        const src = readFileSync(info.file, 'utf8');
        const resolved = resolveExpectedIdentifiers(info, byName, resolveName, src);
        const expected = 'identifiers' in resolved ? resolved.identifiers : null;
        const found = actualDepsOf(src);
        const matches =
            expected !== null && found !== null &&
            expected.length === found.length &&
            expected.every((id, i) => id === found[i]);
        if (!matches) drift.push({ file: info.file, moduleName: info.moduleName, expected, found });
    }
    return drift;
}

/**
 * Programmatic API: compute the injection plan for `<srcDir>` without writing.
 *
 * @param {{ pkg?: string|null, src?: string|null, ignore?: string[] }} [seam]
 * @returns {{
 *   srcDir: string,
 *   plan: { info: import('@awacloud/tool-fw-bundler/modlib').ModuleInfo, addedImports: string[], updatedSrc: string }[],
 *   unparseable: import('@awacloud/tool-fw-bundler/modlib').ModuleInfo[],
 *   unresolved: { file: string, moduleName: string, missing: string[] }[],
 *   ignored: string[],
 *   contentDrift: { file: string, moduleName: string, expected: string[]|null, found: string[]|null }[],
 * }}
 */
export function planDeps(seam = {}) {
    const srcDir = resolveSrcDir(seam);
    const { byName, byFile, unparseable, ignored } = filterScan(
        rawScan(srcDir), srcDir, seam.ignore ?? []
    );
    const resolveName = createNameResolver(srcDir);
    const plan = [];
    const unresolved = [];
    for (const info of byFile.values()) {
        const r = rewriteFile(info, byName, resolveName);
        if (!r) continue;
        if (r.kind === 'skip') {
            unresolved.push({ file: info.file, moduleName: info.moduleName, missing: r.unresolved });
            continue;
        }
        plan.push({ info, addedImports: r.addedImports, updatedSrc: r.updatedSrc });
    }
    const contentDrift = computeContentDrift(byFile, byName, resolveName);
    return { srcDir, plan, unparseable, unresolved, ignored, contentDrift };
}

/**
 * Programmatic API: apply the injection plan to disk.
 *
 * Fully-resolved modules are written even when siblings were skipped — the
 * skip list is returned so the caller can report (and the CLI exit 1).
 *
 * @param {{ pkg?: string|null, src?: string|null, ignore?: string[], dryRun?: boolean }} [seam]
 * @returns {{ srcDir: string, updated: string[], unresolved: { file: string, moduleName: string, missing: string[] }[] }}
 */
export function runDeps(seam = {}) {
    const { srcDir, plan, unresolved } = planDeps(seam);
    const updated = [];
    if (seam.dryRun) return { srcDir, updated, unresolved };
    for (const { info, updatedSrc } of plan) {
        writeFileSync(info.file, updatedSrc, 'utf8');
        updated.push(info.file);
    }
    return { srcDir, updated, unresolved };
}

/**
 * Run the `deps` subcommand CLI. Returns the process exit code.
 * @param {string[]} argv  Args after the `deps` token.
 * @returns {number}
 */
export function runCli(argv) {
    if (wantsHelp(argv)) { printHelp(HELP_USAGE, HELP_FLAGS, HELP_EXAMPLES); return 0; }

    let opts;
    try { opts = parseArgs(argv); }
    catch (err) { console.error('[codegen-deps] ' + err.message); return 2; }

    const srcDir = resolveSrcDir(opts);

    let planned;
    try { planned = planDeps(opts); }
    catch (err) { console.error('[codegen-deps] ' + err.message); return 1; }
    const { plan, unparseable, unresolved, ignored, contentDrift } = planned;

    log(`scanned ${plan.length + unresolved.length} pending module(s) under ${srcDir}`);
    if (ignored.length) log(`${ignored.length} file(s) ignored (generated bundles / --ignore).`);
    if (unparseable.length) {
        warn(`${unparseable.length} file(s) had a non-canonical shape — left untouched:`);
        for (const u of unparseable) warn(`  ${u.file}`);
    }

    /** Print the skipped modules (unresolvable dependency names). */
    const reportSkips = (out) => {
        if (unresolved.length === 0) return;
        out(`[codegen-deps] ${unresolved.length} module(s) SKIPPED — unresolvable dependency:`);
        for (const s of unresolved) {
            out(`  - ${s.moduleName}  (${s.file})  missing: ${s.missing.join(', ')}`);
        }
    };

    if (opts.check) {
        const missing = plan.length + unresolved.length;
        if (missing > 0) {
            console.error(
                `[codegen-deps] FAIL : ${missing} module(s) missing \`deps\` field :`
            );
            for (const { info } of plan) console.error('  - ' + info.moduleName);
            reportSkips((m) => console.error(m));
            return 1;
        }
        // BL-5 content leg: `hasDepsField` only proves the field EXISTS —
        // re-derive what it should hold and diff against what is on disk.
        if (contentDrift.length > 0) {
            console.error(
                `[codegen-deps] FAIL : ${contentDrift.length} module(s) have a stale \`deps\` field (expected vs found) :`
            );
            for (const d of contentDrift) {
                console.error(`  - ${d.moduleName}  (${d.file})`);
                console.error(`      expected: [${(d.expected ?? []).join(', ')}]${d.expected === null ? '  (unresolvable)' : ''}`);
                console.error(`      found:    [${(d.found ?? []).join(', ')}]${d.found === null ? '  (unparseable)' : ''}`);
            }
            console.error(
                '[codegen-deps] Fix: correct the `deps` array (or its import) so it mirrors ' +
                    '`dependencies`, e.g. by re-running `bun cli.ts fw-codegen deps --pkg <dir>` ' +
                    'after removing the stale `deps` field.'
            );
            return 1;
        }
        log('OK : every module with non-empty dependencies has a matching deps field');
        return 0;
    }

    log(`${plan.length} module(s) to update${opts.dryRun ? ' (dry-run)' : ''}`);

    if (opts.dryRun) {
        for (const { info, addedImports } of plan) {
            console.log('');
            console.log(`── ${info.moduleName}  (${info.file})`);
            console.log(`   + ${addedImports.length} import(s), deps: [${info.depNames.join(', ')}]`);
        }
        reportSkips((m) => console.log(m));
        // Frozen contract: --dry-run never fails on content.
        return 0;
    }

    for (const { info, updatedSrc, addedImports } of plan) {
        writeFileSync(info.file, updatedSrc, 'utf8');
        console.log(`✓ ${info.moduleName}  (+${addedImports.length} imports)`);
    }
    console.log(`Done. ${plan.length} file(s) updated.`);
    reportSkips((m) => console.error(m));
    return unresolved.length > 0 ? 1 : 0;
}

if (isMainModule(import.meta.url)) {
    process.exit(runCli(process.argv.slice(2)));
}
