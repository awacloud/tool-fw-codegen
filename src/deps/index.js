/**
 * @fileoverview ONE-SHOT codegen — fills the `deps: [...]` companion field
 * on every module that declares string-form `dependencies`.
 *
 * Ported logic-verbatim from fw's now-deleted `tools/codegen-deps/index.js`
 * (surviving only as the broken copy `packages/front/office/codegen-deps`).
 * The only adaptation is the path-resolution seam: `SRC_DIR` derives from
 * `--src <dir>` or `<--pkg ?? cwd>/src`, so a package points the injector at
 * its own `src/` instead of fw's.
 *
 * Background: the framework keeps `dependencies` as strings for the runtime
 * resolution contract. Bundlers, however, need direct JS references to trace
 * the module graph — the `deps` field bridges that gap: it holds the actual
 * module objects, imported statically by the module file, in the same order as
 * `dependencies`.
 *
 * Usage:
 *     bun cli.ts fw-codegen deps                     # apply
 *     bun cli.ts fw-codegen deps --dry-run           # report only, no writes
 *     bun cli.ts fw-codegen deps --check             # exit 1 if any module is missing or has a stale `deps`
 *     bun cli.ts fw-codegen deps --pkg <dir>         # target another package's src/
 *     bun cli.ts fw-codegen deps --ignore <glob>     # exclude a subtree (repeatable)
 *
 * This is a one-shot: once every module carries `deps`, the invariant is
 * enforced by the bundler's `validate-deps` on every build.
 *
 * Three behaviours make the injector usable from a *consumer* package (office),
 * not only from fw itself:
 *   - generated bundles (`src/bundles/prebuilt/**`) are ignored by default —
 *     they are build artefacts whose `dependencies` name fw modules;
 *   - a dependency name absent from the package's own `src/` is resolved
 *     STATICALLY, in four layers: the descriptor's own package imports, the
 *     entry `main.js` fw imports under its `fw_require` guard, the entry's
 *     named sibling imports under its `pkg_require` guard, and finally a
 *     `pkg_require` NAMESPACE SPREAD followed one hop into the sibling package
 *     (whose public `exports` map yields the specifier);
 *   - a module whose names cannot ALL be resolved is SKIPPED — never
 *     partially rewritten.
 *
 * Nothing is ever imported or executed, and no private deep path into another
 * package is ever emitted.
 */

